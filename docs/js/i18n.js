export const LANGS = Object.keys(STRINGS);

/** Translate with {param} interpolation. Falls back to English, then to the key. */
export function t(lang, key, params = {}) {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (typeof raw !== 'string') return raw; // arrays (level names)
  return raw.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

/** Apply translations to every [data-i18n] / [data-i18n-attr] element under root (browser only). */
export function applyI18n(root, lang) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(lang, el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(lang, key.trim()));
    });
  });
  document.documentElement.lang = lang;
}
